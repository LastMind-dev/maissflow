            <h1>Política de Privacidade</h1>
            <p class="updated">Atualizada em 24 de setembro de 2026.</p>
            <p>Esta página explica como o MaissFlow trata dados pessoais durante o atendimento por WhatsApp e no painel usado pelas equipes responsáveis. Ela se aplica aos canais conectados à plataforma, inclusive ao canal Ouvidoria Municipal de Itapagipe MG.</p>

            <h2>1. Quem decide sobre o tratamento</h2>
            <p>A organização responsável por cada canal de atendimento define a finalidade do atendimento, as informações solicitadas e as regras de conservação dos registros. O MaissFlow fornece a plataforma para executar essas instruções. No canal Ouvidoria Municipal de Itapagipe MG, as solicitações sobre o tratamento dos dados do atendimento devem ser dirigidas ao órgão responsável pela Ouvidoria, por seus canais oficiais.</p>

            <h2>2. Dados tratados</h2>
            <ul>
                <li>Identificação e contato: número de WhatsApp, nome informado no perfil ou no atendimento e, quando fornecido, e-mail.</li>
                <li>Atendimento: mensagens enviadas e recebidas, respostas aos menus, protocolos, histórico da conversa e dados necessários para encaminhar a solicitação.</li>
                <li>Quando o cidadão usa o fluxo de Ouvidoria: identificação anônima ou nominal, CPF, tipo e assunto da manifestação, descrição e, se informados, endereço, bairro e ponto de referência.</li>
                <li>Operação do painel: nome e e-mail dos usuários autorizados, permissões, ações de auditoria e dados técnicos de acesso, como endereço IP.</li>
            </ul>
            <p>Evite enviar informações pessoais além das necessárias para seu pedido. Na versão atual, o fluxo de Ouvidoria não solicita anexos pelo WhatsApp.</p>

            <h2>3. Finalidades</h2>
            <p>Os dados são usados para receber e responder solicitações, executar os fluxos escolhidos pelo cidadão, encaminhar atendimentos à equipe, registrar o histórico e os protocolos, proteger o serviço e permitir a auditoria da operação. A organização responsável pelo canal determina a hipótese legal aplicável a cada serviço público ou atendimento.</p>

            <h2>4. Compartilhamento</h2>
            <p>As mensagens trafegam pela plataforma WhatsApp Business da Meta para permitir a comunicação. Quando o cidadão escolhe registrar uma manifestação no fluxo de Ouvidoria, os dados necessários são encaminhados ao sistema MAISSDoc, que gera o protocolo de acompanhamento. Profissionais autorizados pela organização responsável pelo canal podem acessar os atendimentos conforme suas funções. O tratamento pela Meta também segue as políticas próprias do WhatsApp.</p>

            <h2>5. Segurança e conservação</h2>
            <p>O MaissFlow usa controle de acesso por função, registro de ações, conexão HTTPS e validação das notificações enviadas pela Meta. Os registros são conservados conforme a finalidade do atendimento, as obrigações legais aplicáveis e as orientações da organização responsável pelo canal. Pedidos de eliminação são avaliados conforme essas obrigações; a exclusão não é automática em todos os casos.</p>

            <h2>6. Direitos dos titulares</h2>
            <p>Você pode solicitar à organização responsável pelo atendimento informações sobre o uso de seus dados, acesso, correção e, quando cabível, eliminação ou outros direitos previstos na Lei Geral de Proteção de Dados. Para o canal Ouvidoria Municipal de Itapagipe MG, procure os canais oficiais da Ouvidoria ou inicie contato pelo número <a href="https://wa.me/5534920006744">+55 34 92000-6744</a>. Ao fazer uma solicitação, informe o protocolo, se tiver um, sem enviar documentos sensíveis em canais públicos.</p>

            <h2>7. Atualizações</h2>
            <p>Esta política poderá ser atualizada quando os fluxos, integrações ou regras aplicáveis mudarem. A versão vigente ficará disponível nesta página.</p>
